def seed():
    db = SessionLocal()
    try:
        current_count = db.query(Question).count()
        if current_count >= len(QUESTIONS):
            print(f"В базе уже {current_count} вопросов. Пропускаю.")
            return

        # Если база пустая или устаревшая — перезаливаем
        if current_count > 0:
            print(f"Найдено {current_count} вопросов. Перезаливаю на {len(QUESTIONS)}...")
            db.query(Question).delete()
            db.commit()

        for text, lat, lon, correct, cat, diff in QUESTIONS:
            db.add(Question(
                text=text,
                latitude=lat,
                longitude=lon,
                correct_text=correct,
                category=cat,
                difficulty=diff,
            ))
        db.commit()
        print(f"✅ Добавлено {len(QUESTIONS)} вопросов в базу.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()