def seed():
    db = SessionLocal()
    try:
        # Если вопросы уже есть — не дублируем
        if db.query(Question).count() > 0:
            print(f"В базе уже {db.query(Question).count()} вопросов. Пропускаю.")
            return

        for text, lat, lon, correct, cat, diff in QUESTIONS:
            db.add(Question(
                text=text,
                latitude=lat,
                longitude=lon,
                correct_text=correct,
                category=cat,
                difficulty=diff,
            ))
        db.commit()
        print(f"✅ Добавлено {len(QUESTIONS)} вопросов в базу.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()